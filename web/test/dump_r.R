# Writes the R implementation's results for an export, so web/test/compare.mjs can check the JS port against them.
# Usage: Rscript web/test/dump_r.R parsed_export.rds OUT_DIR START END      (dates as YYYY-MM-DD)
args <- commandArgs(trailingOnly = TRUE)
rds <- args[1]; out <- args[2]; start <- as.Date(args[3]); end <- as.Date(args[4])
root <- normalizePath(file.path(dirname(sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE))), "..", ".."))
for (f in c("parse_export.R", "metrics.R")) source(file.path(root, "cli", f))
dir.create(out, showWarnings = FALSE, recursive = TRUE)
w <- function(d, name) write.csv(d, file.path(out, paste0(name, ".csv")), row.names = FALSE)
x <- readRDS(rds)
runs <- build_runs(x, start, end)
r <- runs[, setdiff(names(runs), "hr_curve")]; r$date <- as.character(r$date); w(r, "runs")
max_hr <- estimate_max_hr(x$birth_date, max(runs$date)); if (is.na(max_hr)) max_hr <- max(runs$hr_max, na.rm = TRUE)
rest_hr <- estimate_rest_hr(x$records, max(runs$date)); if (is.na(rest_hr)) rest_hr <- 0
w(zone_seconds(runs, max_hr, rest_hr), "zones")
w(data.frame(max_hr = max_hr, rest_hr = rest_hr, labels = paste(zone_labels(max_hr, rest_hr), collapse = "|")), "zoneinfo")
w(monthly_summary(runs), "ms_all"); w(monthly_summary(runs, "outdoor"), "ms_out"); w(monthly_summary(runs, "indoor"), "ms_in")
wk <- weekly_load(runs, prior_runs(x, start)); wk$week <- as.character(wk$week); w(wk, "wk")
rg <- route_groups(runs); w(data.frame(date = as.character(rg$date), route_mi = rg$route_mi), "rg")
w(perf_summary(runs), "perf")
w(weather_bins(runs, "F"), "wbF"); w(weather_bins(runs, "C"), "wbC")
wr <- weather_runs(runs); if (!is.null(wr)) w(data.frame(date = as.character(wr$date), hr_resid = wr$hr_resid), "wr")
